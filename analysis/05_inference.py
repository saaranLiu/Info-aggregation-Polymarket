    Dv = dd.D.to_numpy(); mv = dd.m.to_numpy(); Yv = dd.Y.to_numpy()
    newrun = np.r_[True, (Dv[1:] != Dv[:-1]) | (mk[1:] != mk[:-1])]; run_id = np.cumsum(newrun) - 1; R = run_id.max() + 1
    run_len = np.bincount(run_id); run_D = Dv[newrun]; run_mk = mk[newrun]
    obs_within = 1e4 * ((Dv - pd.Series(Dv).groupby(mk).transform("mean").to_numpy()) * (Yv - mv)).mean()
    perm = []
    for r in range(NPERM):
        key = np.random.default_rng(SEED + r).random(R); o = np.lexsort((key, run_mk))        # permute runs within market
        Dp = np.repeat(run_D[o], run_len[o])
        perm.append(1e4 * ((Dp - pd.Series(Dp).groupby(mk).transform("mean").to_numpy()) * (Yv - mv)).mean())
    perm = np.array(perm)
    save(pd.DataFrame([dict(grp=grp, observed_within_bp=obs_within, null_mean_bp=perm.mean(), null_sd_bp=perm.std(ddof=1), null_lo_bp=np.percentile(perm, 2.5), null_hi_bp=np.percentile(perm, 97.5), n_runs=R, n_perm=NPERM)]), f"inf_B_perm_runs_{grp}.csv")
