    A = pd.DataFrame(rows); save(A, f"inf_A_clusters_{grp}.csv")
    store[grp] = (d, cells, A)
    # ---- B1 stratified Y permutation (market-level sums make this exact and cheap)
    g = d.groupby("condition_id").agg(cat=("cat", "first"), Y=("Y", "first"), n=("D", "size"), SD=("D", "sum"), SDm=("D", lambda s: 0.0), mbar=("m", "mean"), res_ts=("res_ts", "first"))
    g["SDm"] = d.assign(Dm=d.D * d.m).groupby("condition_id").Dm.sum()
    g["dec"] = pd.qcut(g.mbar.rank(method="first"), 10, labels=False); g["q"] = pd.to_datetime(g.res_ts, unit="s").dt.to_period("Q").astype(str)
    g["stratum"] = g.cat + "|" + g.dec.astype(str) + "|" + g.q
    N = g.n.sum()
    def comps(Yv, sub=None):
        gg = g if sub is None else g[sub]; Nn = gg.n.sum()
        tot = (Yv[gg.index] * gg.SD - gg.SDm).sum() / Nn; btw = (gg.SD * (Yv[gg.index] - gg.mbar)).sum() / Nn
        return 1e4 * tot, 1e4 * btw, 1e4 * (tot - btw)
    subs = [("pooled", None)] + ([(c, g.cat == c) for c in ["Politics", "Crypto"]] if grp == "YesNo" else [])
    rows = []
    for sname, sub in subs:
        obs = comps(g.Y, sub); perm = []
        for r in range(NPERM):
            Yp = g.groupby("stratum").Y.transform(lambda s: s.sample(frac=1, random_state=SEED + r).to_numpy())
            perm.append(comps(Yp, sub))
        perm = np.array(perm)
        for j, nm in enumerate(["info_total", "info_between", "info_within"]):
            rows.append(dict(grp=grp, cell=sname, component=nm, observed_bp=obs[j], null_mean_bp=perm[:, j].mean(), null_sd_bp=perm[:, j].std(ddof=1),
                             null_lo_bp=np.percentile(perm[:, j], 2.5), null_hi_bp=np.percentile(perm[:, j], 97.5), p_two_sided=float((np.abs(perm[:, j] - perm[:, j].mean()) >= abs(obs[j] - perm[:, j].mean())).mean()), n_perm=NPERM))
