            se2, G1, G2 = twoway_se_mean(x, dd.ev_cluster.to_numpy()[ok], dd.cal_week.to_numpy()[ok]); row["se_twoway_event_week_bp"] = 1e4 * se2; row["G_cal_week"] = G2
