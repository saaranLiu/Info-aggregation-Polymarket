COLS = {"info": lambda d: d.D * (d.Y - d.m), "eff": lambda d: d.D * (d.p - d.m), "RS": lambda d: -d.edge,
        "PI_100": lambda d: d.D * (d.ma - d.m), "over_100": lambda d: d.D * (d.ma - d.Y)}

def draws(x, cl, B=BB, seed=SEED):
    """Cluster-bootstrap draws of a mean. x: values, cl: cluster codes (0..G-1)."""
    x = np.asarray(x, float); ok = ~np.isnan(x); x = x[ok]; cl = pd.Series(np.asarray(cl)[ok]).astype("category").cat.codes.to_numpy()
    G = cl.max() + 1; S = np.bincount(cl, x, G); N = np.bincount(cl, None, G).astype(float)
    r = np.random.default_rng(seed); out = np.empty(B)
    for b0 in range(0, B, 200):
        nb = min(200, B - b0); Wb = r.multinomial(G, np.full(G, 1 / G), size=nb).astype(float); out[b0:b0 + nb] = (Wb @ S) / (Wb @ N)
    return x.mean(), out, G

